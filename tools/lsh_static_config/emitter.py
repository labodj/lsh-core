"""Filesystem emission for generated headers."""

from __future__ import annotations

import sys
from pathlib import Path
from stat import S_IMODE
from tempfile import NamedTemporaryFile
from typing import TYPE_CHECKING

from .errors import fail
from .headers import generated_files
from .lockfile import read_lock
from .validation import validate_output_paths

if TYPE_CHECKING:
    from collections.abc import Sequence

    from .models import ProjectConfig


def _stale(path: Path, content: str, *, generated_header: bool = False) -> bool:
    """Compare text before any project output is published."""
    try:
        existing = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return True
    except (OSError, UnicodeError) as exc:
        fail(f"Cannot read {path}: {exc}")
    if (
        generated_header
        and "// Generated by tools/generate_lsh_static_config.py " not in existing
    ):
        fail(f"{path} already exists and is not an lsh-core generated header.")
    return existing != content


def write_text(path: Path, content: str) -> None:
    """Replace an existing file only after its entire replacement is on disk."""
    try:
        mode = path.stat().st_mode
    except FileNotFoundError:
        with path.open("x", encoding="utf-8") as output:
            output.write(content)
        return
    with NamedTemporaryFile(dir=path.parent, delete=False) as output:
        temporary = Path(output.name)
        try:
            output.write(content.encode("utf-8"))
            output.flush()
            temporary.chmod(S_IMODE(mode))
            temporary.replace(path)
        finally:
            temporary.unlink(missing_ok=True)


def write_if_changed(path: Path, content: str, *, check: bool) -> bool:
    """Write one generated file, or report staleness in check mode."""
    if not _stale(path, content):
        return False
    if check:
        sys.stderr.write(f"stale: {path}\n")
        return True
    path.parent.mkdir(parents=True, exist_ok=True)
    write_text(path, content)
    return True


def generate(
    project: ProjectConfig,
    selected_devices: Sequence[str],
    *,
    check: bool = False,
) -> int:
    """Generate headers for the selected devices, optionally as a stale check."""
    if not check:
        validate_output_paths(project)
    files = generated_files(project, selected_devices)
    if project.settings.id_lock_file.exists():
        read_lock(project.settings.id_lock_file)
    files[project.settings.id_lock_file] = project.id_lock_content
    stale = {
        path: content
        for path, content in files.items()
        if _stale(path, content, generated_header=path != project.settings.id_lock_file)
    }
    for path, content in stale.items():
        if check:
            sys.stderr.write(f"stale: {path}\n")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            write_text(path, content)
    return int(check and bool(stale))
